HOST = 'registry.example.test:30500'


def runtime_config(path, version=2):
    plugin = 'io.containerd.grpc.v1.cri' if version == 2 else 'io.containerd.cri.v1.images'
    path.write_text(f'version = {version}\n[plugins."{plugin}".registry]\n'
                    'config_path = "/var/lib/rancher/k3s/agent/etc/containerd/certs.d"\n')


@pytest.mark.parametrize('version', [2, 3])
def test_http_and_https_reload_preserve_ca_and_survive_k3s_regeneration(tmp_path, version):
    config = tmp_path / 'config.toml'; runtime_config(config, version)
    source = tmp_path / 'original'; source.mkdir()
    target = tmp_path / 'managed'; target.mkdir()
    original = f'# File generated by k3s. DO NOT EDIT.\nserver = "https://{HOST}/v2"\nca = ["/etc/registry-ca.crt"]\n[host."http://{HOST}/v2"]\ncapabilities = ["pull", "resolve"]\n'
    (source / 'hosts.toml').write_text(original)
    apply_transport(target, HOST, True, config, source)
    actual = tomllib.loads((target / 'hosts.toml').read_text())
    assert actual['server'] == f'http://{HOST}/v2'
    assert actual['ca'] == ['/etc/registry-ca.crt']
    assert all(key.startswith('http://') for key in actual['host'])
    assert (source / 'hosts.toml').read_text() == original
    apply_transport(target, HOST, False, config, source)
    assert tomllib.loads((target / 'hosts.toml').read_text())['server'] == f'https://{HOST}/v2'
    # k3s regenerates only its colon directory; the preferred underscore directory remains managed.
    (source / 'hosts.toml').write_text(original)
    apply_transport(target, HOST, True, config, source)
    assert (target / 'hosts.toml').read_text().startswith(MARKER)
    assert tomllib.loads((target / 'hosts.toml').read_text())['server'].startswith('http://')


def test_unsupported_config_and_symlinks_are_rejected(tmp_path):
    config = tmp_path / 'config.toml'; config.write_text('version=2')
    with pytest.raises(ValueError):
        apply_transport(tmp_path, HOST, True, config)
    runtime_config(config)
    elsewhere = tmp_path / 'private'; elsewhere.write_text('unchanged')
    (tmp_path / 'hosts.toml').symlink_to(elsewhere)
    with pytest.raises(ValueError):
        apply_transport(tmp_path, HOST, True, config)
    assert elsewhere.read_text() == 'unchanged'
    with pytest.raises(ValueError):
        render_hosts('', '../docker.io', True)


