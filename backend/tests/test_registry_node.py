def test_node_sync_uses_rotated_service_account_token(tmp_path, monkeypatch):
    import backend.worker.registry_node as node_module
    token = tmp_path / 'token'; token.write_text('first-token')
    ready = tmp_path / 'ready'
    actual_path = Path
    def local_path(value):
        return token if value.endswith('/serviceaccount/token') else ready if value == '/tmp/registry-node-ready' else actual_path(value)
    monkeypatch.setattr(node_module, 'Path', local_path)
    monkeypatch.setattr(node_module.ssl, 'create_default_context', lambda **kwargs: None)
    monkeypatch.setattr(node_module, 'apply_transport', lambda *args: None)
    for key, value in {'REGISTRY_HOST': HOST, 'POD_NAMESPACE': 'koyorina-build', 'NODE_NAME': 'node-1'}.items():
        monkeypatch.setenv(key, value)
    submitted_tokens = []
    class Response:
        def raise_for_status(self): pass
        def json(self):
            return {'data': {'transport': json.dumps({'host': HOST, 'http': True})}}
    class Client:
        def __init__(self, **kwargs): self.headers = {}
        async def __aenter__(self): return self
        async def __aexit__(self, *args): pass
        async def get(self, *args): return Response()
        async def patch(self, *args, **kwargs):
            submitted_tokens.append(self.headers['Authorization'])
            return Response()
    monkeypatch.setattr(node_module.httpx, 'AsyncClient', Client)
    turns = 0
    async def sleep(seconds):
        nonlocal turns
        turns += 1
        if turns == 2:
            raise asyncio.CancelledError
        token.write_text('rotated-token')
    monkeypatch.setattr(node_module.asyncio, 'sleep', sleep)
    async def check():
        with pytest.raises(asyncio.CancelledError):
            await node_module.run()
    asyncio.run(check())
    assert submitted_tokens == ['Bearer first-token', 'Bearer rotated-token']
