@pytest.mark.parametrize('failure', ['missing', 'stale', 'wrong_hash', 'missing_node'])
def test_publication_waits_for_every_node_to_apply_exact_transport(failure):
    async def check():
        c = FakeController()
        original = c.kube
        async def kube(method, resource, name='', **kwargs):
            if resource == 'daemonsets':
                return None if failure == 'missing' else {'status': {'desiredNumberScheduled': 2}}
            if resource == 'pods':
                return {'items': [{'metadata': {}, 'spec': {'nodeName': node}} for node in ('node-1', 'node-2')]}
            if resource == 'leases':
                stamp = datetime.now(timezone.utc) - timedelta(seconds=60 if failure == 'stale' else 0)
                return {'items': [{'metadata': {'annotations': {'node': node,
                    'transport-hash': 'wrong' if failure == 'wrong_hash' else transport_hash(HOST, True)}},
                    'spec': {'renewTime': stamp.isoformat()}} for node in
                    (('node-1',) if failure == 'missing_node' else ('node-1', 'node-2'))]}
            return await original(method, resource, name, **kwargs)
        c.kube = kube
        with patch('backend.worker.publication_controller.asyncio.sleep', new=AsyncMock()):
            with pytest.raises(HTTPException) as error:
                await c.ensure_transport({'kind': 'private', 'host': HOST, 'http': True})
        assert error.value.status_code == 422
    asyncio.run(check())


def test_missing_node_sync_does_not_replace_running_publication():
    from backend.tests.test_publication import source, BUILD, SHA, PROJECT, TENANT
    from backend.worker.publication_controller import PublishInput
    async def check():
        c = FakeController()
        build = await c.submit(BUILD, source())
        build.update(status='succeeded', digest=SHA)
        await c.record('build-' + BUILD, build)
        name = 'published-' + PROJECT
        previous = {'status': 'running', 'current': {'build_id': BUILD}}
        await c.record(name, previous)
        original = c.kube
        async def kube(method, resource, name='', **kwargs):
            if resource == 'daemonsets':
                return None
            return await original(method, resource, name, **kwargs)
        c.kube = kube
        with pytest.raises(HTTPException) as error:
            await c.publish(PROJECT, PublishInput(tenant_id=TENANT, build_id=BUILD,
                image=build['image'].rsplit(':', 1)[0] + '@' + SHA,
                app_origin='https://koyorina.test', forward_secret='f' * 40))
        assert error.value.status_code == 422
        assert await c.record(name) == previous
        assert (True, 'deployments', name) not in c.store
        assert (True, 'persistentvolumeclaims', name + '-data') not in c.store
    asyncio.run(check())


